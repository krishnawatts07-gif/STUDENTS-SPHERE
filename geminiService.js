import { GoogleGenerativeAI } from "@google/generative-ai";

// Fetch the API key from Vite environment variables
const apiKey = import.meta.env?.VITE_GEMINI_API_KEY || (typeof process !== 'undefined' ? process.env?.VITE_GEMINI_API_KEY : undefined);

// Initialize the Google Generative AI client
const genAI = new GoogleGenerativeAI(apiKey);

/**
 * Sends a message to the gemini-1.5-flash model with multi-turn chat history.
 * 
 * @param {Array<{role: string, content?: string, text?: string}>} history - Array of previous chat messages.
 * @param {string} newMessage - The new user prompt to send.
 * @returns {Promise<string>} The text response generated by Gemini.
 */
export const sendChatMessage = async (history = [], newMessage) => {
  try {
    if (!apiKey) {
      throw new Error("API key is missing. Please set VITE_GEMINI_API_KEY in your environment.");
    }

    if (!newMessage || typeof newMessage !== "string") {
      throw new Error("newMessage must be a non-empty string.");
    }

    // Get the gemini-3.6-flash model instance
    const model = genAI.getGenerativeModel({ model: "gemini-3.6-flash" });

    // Format input history to match @google/generative-ai SDK expectations:
    // [{ role: 'user' | 'model', parts: [{ text: string }] }]
    const formattedHistory = history.map((msg) => ({
      role: msg.role === "assistant" || msg.role === "model" ? "model" : "user",
      parts: [{ text: msg.text || msg.content || (typeof msg === "string" ? msg : "") }]
    }));

    // Start chat session with formatted history
    const chat = model.startChat({
      history: formattedHistory
    });

    // Send the new user message
    const result = await chat.sendMessage(newMessage);
    const response = await result.response;
    
    // Return the response text
    return response.text();
  } catch (error) {
    console.error("Error generating response from Gemini:", error.message);
    throw error;
  }
};
